#!/usr/bin/env bash
# Generate the secrets shared by the librechat and code-interpreter stacks and
# append them to both host .env files.
#
# The two files hold the two halves of one Ed25519 keypair: LibreChat signs a
# short-lived token for every code request with the private key, and the
# Code Interpreter API verifies it with the public one. Generating them
# separately would produce two keys that cannot verify each other, which is
# why this is one script rather than two .env.example recipes.
#
# Usage (on the server, as root):
#   scripts/codeapi-secrets.sh <code-interpreter/.env> <librechat/.env>
#
# Refuses to touch a file that already has any of these keys: rotating means
# deleting the old lines first, on purpose. Needs only openssl and coreutils.
set -euo pipefail

codeapi_env=${1:?usage: $0 <code-interpreter .env> <librechat .env>}
librechat_env=${2:?usage: $0 <code-interpreter .env> <librechat .env>}

for f in "$codeapi_env" "$librechat_env"; do
  if [[ -f "$f" ]] && grep -qE '^(CODEAPI_|SANDBOX_EXECUTION_MANIFEST_|LIBRECHAT_CODE_)' "$f"; then
    echo "!! $f already has Code Interpreter keys; remove them to rotate." >&2
    exit 1
  fi
done

b64url() { basenc --base64url -w0 | tr -d '='; }
rand() { openssl rand -hex 32; }

# Ed25519 DER layouts are fixed: the last 32 bytes of the PKCS#8 private key
# are the seed (JWK `d`), the last 32 of the SPKI public key are `x`.
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

openssl genpkey -algorithm ed25519 -outform DER -out "$tmp/jwt.der"
openssl pkey -inform DER -in "$tmp/jwt.der" -pubout -outform DER -out "$tmp/jwt.pub.der"
jwt_d=$(tail -c 32 "$tmp/jwt.der" | b64url)
jwt_x=$(tail -c 32 "$tmp/jwt.pub.der" | b64url)
kid="codeapi-$(date -u +%Y%m%d)"

openssl genpkey -algorithm ed25519 -outform DER -out "$tmp/manifest.der"
openssl pkey -inform DER -in "$tmp/manifest.der" -pubout -outform DER -out "$tmp/manifest.pub.der"

umask 077
cat >>"$codeapi_env" <<EOF

# --- generated by scripts/codeapi-secrets.sh on $(date -u +%F) ---
CODEAPI_JWT_JWKS_JSON='{"keys":[{"kty":"OKP","crv":"Ed25519","x":"$jwt_x","kid":"$kid","alg":"EdDSA","use":"sig"}]}'
CODEAPI_EXECUTION_MANIFEST_PRIVATE_KEY=$(base64 -w0 "$tmp/manifest.der")
SANDBOX_EXECUTION_MANIFEST_PUBLIC_KEY=$(base64 -w0 "$tmp/manifest.pub.der")
CODEAPI_INTERNAL_SERVICE_TOKEN=$(rand)
CODEAPI_EGRESS_GRANT_SECRET=$(rand)
CODEAPI_BRIDGE_TOKEN=$(rand)
REDIS_PASSWORD=$(rand)
STORAGE_ACCESS_KEY=$(openssl rand -hex 10)
STORAGE_SECRET_KEY=$(rand)
EOF

cat >>"$librechat_env" <<EOF

# --- generated by scripts/codeapi-secrets.sh on $(date -u +%F) ---
CODEAPI_JWT_KID=$kid
CODEAPI_JWT_PRIVATE_JWK_JSON='{"kty":"OKP","crv":"Ed25519","x":"$jwt_x","d":"$jwt_d","kid":"$kid","alg":"EdDSA"}'
EOF

chmod 600 "$codeapi_env" "$librechat_env"
echo "Wrote Code Interpreter secrets to $codeapi_env and $librechat_env (kid $kid)."
